GENERIC = [
    "Тримайте жарт, поки я гортаю логи.",
    "Розслідую. Це та частина, де в детективі показують дошку з нитками.",
    "Дивлюсь метрики. Поки що всі підозрювані мають алібі.",
    "Кожен інцидент унікальний. Рівно до моменту, коли знаходиш такий самий постмортем.",
]

PREFIX = ":coffee: "
_last: dict[str, str] = {}  # тред -> попередній жарт, щоб не повторюватись підряд


def pick(alertname: str, thread_id: str = "") -> str | None:
    """Жарт до цього типу алерту. None, якщо гумор вимкнено."""
    if not JOKES_ENABLED:
        return None

    options = BY_ALERT.get(alertname, GENERIC)
    previous = _last.get(thread_id)
    fresh = [joke for joke in options if joke != previous] or options
    chosen = random.choice(fresh)
    if thread_id:
        _last[thread_id] = chosen
    return PREFIX + chosen
